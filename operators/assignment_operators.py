"""Assignment operators"""

x = 5

x += 5      # same as x = x + 5, Result = 10
x -= 2      # same as x = x - 2, Result = 8
x *= 2      # same as x = x * 2, Result = 16
x /= 2      # same as x = x / 2, Result = 8.0
x //= 3     # same as x = x // 3, Result = 2.0
x %= 2      # same as x = x % 2, Result = 0.0
x **= 1     # same as x = x ** 2, Result = 0.0
