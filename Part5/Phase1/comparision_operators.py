"""Demonstrate the comparison operators."""


first_number = 10
second_number = 25

print(f"==    : {first_number == second_number}")
print(f"!=    : {first_number != second_number}")
print(f"<     : {first_number < second_number}")
print(f">     : {first_number > second_number}")
print(f"<=    : {first_number <= second_number}")
print(f">=    : {first_number >= second_number}")
