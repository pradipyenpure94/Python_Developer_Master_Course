"""Demonstrate the logical operators."""

# Logical AND:
print(f"Example of Logical AND: {10 > 3 and 10 == 4}")
print(f"Example of Logical AND: {10 > 3 and 10 == 10}")
print("-" * 40)
print()

# Logical OR:
print(f"Logical OR: {10 > 3 or 10 == 4}")
print(f"Logical OR: {10 > 13 or 10 == 10}")
print(f"Logical OR: {10 > 13 or 10 == 4}")
print()

# Logical NOT
print(f"Logical NOT: {not True}")
print(f"Logical NOT: {not False}")
print(f"Logical NOT: {not (10==0)}")
