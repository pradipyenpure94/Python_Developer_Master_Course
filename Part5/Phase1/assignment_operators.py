"""Demonstrate the assignment operators."""

value = 10
print(f"Equal to Assign         : {value}")

value += 10
print(f"Addition and Assign     : {value}")

value -= 5
print(f"Subtraction and Assign  : {value}")

value *= 4
print(f"Multiply and Assign     : {value}")

value /= 2
print(f"Division and Assign     : {value}")

value //= 4
print(f"Floor Divide and Assign : {value}")

value %= 4
print(f"Modulus and Assign      : {value}")

value **= 2
print(f"Exponent and Assign     : {value}")
