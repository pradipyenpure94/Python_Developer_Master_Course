"""Design and develop custom functions."""

from numbers import Real


def add(first_number: Real, second_number: Real) -> Real:
    """Return the addition of two numbers."""
    return first_number + second_number


def sub(first_number: Real, second_number: Real) -> Real:
    """Return the subtraction of two numbers."""
    return first_number - second_number


def mul(first_number: Real, second_number: Real) -> Real:
    """Return the multiplication of two numbers."""
    return first_number * second_number


def div(first_number: Real, second_number: Real) -> float:
    """Return the division of two numbers."""
    return first_number / second_number
